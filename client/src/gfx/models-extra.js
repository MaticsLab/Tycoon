// Books standing on a shelf from x0 to x1 at height y, depth z..z+d.
function books(x0, x1, y, z, d, seed = 0) {
  const cols = ['#d9534f', '#4a90d9', '#5cb85c', '#f0ad4e', '#9b59b6', '#f4f1ea', '#e67e22', '#3fb5a3'];
  const out = [];
  let x = x0;
  for (let b = 0; ; b++) {
    const w = 0.05 + ((b + seed) % 3) * 0.02, h = 0.2 + ((b * 5 + seed) % 3) * 0.04;
    if (x + w > x1) break;
    out.push([x, y, z, w, h, d, cols[(b * 3 + seed) % cols.length]]);
    x += w + 0.006;
  }
  return out;
}
